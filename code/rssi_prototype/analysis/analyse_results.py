"""Summarise the RSSI batch results into tables (Markdown) and figures (PNG).

Usage:  python analyse_results.py [results_folder]
        (default: ../results next to this script)
Writes: <results>/analysis/summary.md and <results>/analysis/*.png

Reads whatever exists of: main/batch_main.csv, oat/batch_oat.csv, series/series_*.csv,
series/lgu_*.csv, main/batch_long.csv, wind/batch_wind_direction.csv, main/batch_saturating.csv.
Column orders: results/COLUMNS.csv and results/series/COLUMNS.csv (the CSVs have no header).
Needs pandas and matplotlib. No significance tests: replicate spread is reported as SD and range.
"""
import sys, os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(HERE, "..", "results")
OUT = os.path.join(RES, "analysis"); os.makedirs(OUT, exist_ok=True)
COLS = ["experiment", "oat_case", "strategy", "n_half", "seed", "share_ever", "share_infested_end",
        "cum_kdays", "apps_chem", "apps_bio", "cane_total", "harvest_count", "max_D"]
SCOLS = ["series_tag", "strategy", "n_half", "oat_case", "seed", "cycle", "share_infested", "share_ever",
         "mean_density", "apps_chem", "apps_bio", "lv1", "lv2", "lv3", "n_farms"]
LCOLS = ["series_tag", "seed", "lgu_idx", "lgu_name", "cane_cells", "ever_cells", "sra_valid_ha"]
ORDER = ["none", "chemical", "biological", "hybrid"]
OAT_LABELS = {0: "baseline", 1: "settlement survival 0.01", 2: "settlement survival 0.10",
              3: "neighbour transmission x0.25", 4: "neighbour transmission x4", 5: "long jump 0",
              6: "long jump 0.2", 7: "parasitism 0", 8: "parasitism 0.668", 9: "bio:chem ratio 0.8",
              10: "bio:chem ratio 1.0", 11: "level thresholds x0.5 (200 insects/leaf = K)", 12: "level thresholds x2 (50 insects/leaf = K)",
              13: "trigger T = 2", 14: "trigger T = 3", 15: "re-treatment 7 d", 16: "re-treatment 28 d",
              17: "wind bias 0.5", 18: "wind bias 1.0"}
SRA_SHARE = 72103.42 / 239215.62   # validated / planted, Negros, 2 Oct 2026 (SRA FOI reply, Tables I and III)
md = ["# RSSI batch results: summary", "",
      f"Source folder: `results/{os.path.basename(RES)}`. Generated by `analysis/analyse_results.py` from the run CSVs.", ""]


def read(path, cols):
    p = os.path.join(RES, path)
    if not os.path.exists(p) or os.path.getsize(p) == 0:
        return None
    df = pd.read_csv(p, header=None, names=cols)
    return df


def label(r):
    return r["strategy"] if r["strategy"] in ("none", "biological") else f'{r["strategy"]} (n_half {int(r["n_half"]) or "none"})'


def summarise(df):
    df = df.copy()
    df["cane_per_ha"] = df.cane_total / df.harvest_count.replace(0, np.nan)
    g = df.groupby(["strategy", "n_half"])
    t = g.agg(n=("seed", "size"), load_mean=("cum_kdays", "mean"), load_sd=("cum_kdays", "std"),
              load_min=("cum_kdays", "min"), load_max=("cum_kdays", "max"),
              ever_mean=("share_ever", "mean"), end_mean=("share_infested_end", "mean"),
              chem=("apps_chem", "mean"), bio=("apps_bio", "mean"), cane=("cane_per_ha", "mean"),
              maxD=("max_D", "max")).reset_index()
    t["label"] = t.apply(label, axis=1)
    return t.sort_values("load_mean")


def table(t):
    rows = ["| Rank | Configuration | n | Cumulative pest load, K-days: mean (SD) [min-max] | Share ever infested | Share infested at end | Chemical apps | Biological apps | Cane t/ha | Max density (K) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(t.itertuples(), 1):
        sd = 0 if pd.isna(r.load_sd) else r.load_sd
        rows.append(f"| {i} | {r.label} | {r.n} | {r.load_mean:,.0f} ({sd:,.0f}) [{r.load_min:,.0f}-{r.load_max:,.0f}] | "
                    f"{r.ever_mean:.3f} | {r.end_mean:.3f} | {r.chem:,.0f} | {r.bio:,.0f} | {r.cane:.2f} | {r.maxD:.3f} |")
    return rows


# 1 Main comparison
main = read("main/batch_main.csv", COLS)
if main is not None:
    main = main[main.experiment == "main"]
    t = summarise(main)
    md += ["## 1. Main comparison", "", *table(t), "",
           "Lower load ranks first. Applications count farm-level treatment events (one per farm), not hectares.", ""]
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.bar(t.label, t.load_mean, yerr=t.load_sd.fillna(0), color="#4a7fb5", capsize=3)
    ax.set_ylabel("Cumulative pest load (K-days)"); ax.set_yscale("log")
    area = "window A (Cadiz, Manapla, Victorias)" if os.path.basename(RES.rstrip("/\\")) == "A" else "all of Negros"
    ax.set_title(f"Strategies over 1,095 days, {area} (mean, SD)")
    plt.xticks(rotation=30, ha="right"); plt.tight_layout(); fig.savefig(os.path.join(OUT, "main_load.png"), dpi=200); plt.close(fig)
    md += ["![main](main_load.png)", ""]

# 2 OAT sensitivity: does the strategy ranking change?
oat = read("oat/batch_oat.csv", COLS)
if oat is not None:
    m = oat.groupby(["oat_case", "strategy"]).cum_kdays.mean().unstack()
    m = m[[s for s in ORDER if s in m.columns]]
    # Ties: with 1 run per cell, two strategies whose loads differ by less than the largest relative
    # replicate range seen in the main comparison ((max - min) / mean, 'none' excluded) are not ranked.
    TIE = 0.0
    if main is not None:
        tt = summarise(main); tt = tt[tt.strategy != "none"]
        TIE = float(((tt.load_max - tt.load_min) / tt.load_mean).max())
    def grouped(r):
        v = r.dropna().sort_values(); out = []
        for k, x in v.items():
            if out and x <= out[-1][1] * (1 + TIE): out[-1][0].append(k); out[-1][1] = x
            else: out.append([[k], x])
        return [sorted(g) for g, _ in out]
    def show(gs): return " < ".join(" ≈ ".join(g) for g in gs)
    # Baseline ranking from the main comparison (2 replicates, n_half 20 for chemical and hybrid), not
    # from the single case-0 run.
    base = None
    if main is not None:
        b0 = main[(main.n_half == 20) | main.strategy.isin(["none", "biological"])].groupby("strategy").cum_kdays.mean()
        base = grouped(b0[[c for c in m.columns if c in b0.index]])
    elif 0 in m.index:
        base = grouped(m.loc[0])
    nmin, nmax = oat.groupby(["oat_case", "strategy"]).size().agg(["min", "max"])
    md += ["## 2. One-at-a-time sensitivity", "",
           f"Mean cumulative pest load per strategy (n = {nmin}-{nmax} runs per cell: a screen, not an estimate). "
           "'Ranking' lists strategies from lowest to highest load; 'changes?' compares with the baseline ranking of section 1 (n_half 20, 2 replicates: " + (show(base) if base else "n/a") + "). "
           f"Strategies within {TIE:.0%} of each other are shown as tied (≈): the largest relative range between the 2 "
           "replicates of any configuration in section 1.", "",
           "| Case | Assumption changed | " + " | ".join(m.columns) + " | Ranking | Changes? |",
           "|---|---|" + "---|" * len(m.columns) + "---|---|"]
    for case, r in m.iterrows():
        rank = grouped(r)
        if r.isna().any():
            ch = "incomplete"
        else:
            ch = "" if base is None else ("no" if rank == base else "**yes**")
        md.append(f"| {case} | {OAT_LABELS.get(case, case)} | " + " | ".join(f"{v:,.0f}" for v in r) + f" | {show(rank)} | {ch} |")
    md.append("")

# Seeded runs (13 Nov): seeds on day 233 (22 May 2025); FOI Table I date 2 Oct 2026 = day 731
D731 = 731
N_CANE = 356869   # mapped cane cells, island (harvest count of the no-pest run / 2)
SEEDED = os.path.exists(os.path.join(RES, "series", "lgu_hybrid_baseline_d731.csv"))

# 3 Time-scale check
ser = read("series/series_hybrid_baseline.csv", SCOLS)
if ser is not None:
    s = ser.groupby("cycle").share_ever.agg(["mean", "min", "max"])
    cross = s.index[s["mean"] >= SRA_SHARE]
    md += ["## 3. Time-scale check (hybrid, baseline)", "",
           f"Reference: SRA validated RSSI area on 2 Oct 2026 = {SRA_SHARE:.1%} of Negros planted cane (FOI). "
           "The model's share is of mapped cane cells, which over-represent planted area about 1.5 times.", "",
           f"- Mean share ever infested reaches {SRA_SHARE:.1%} on day **{int(cross[0]) if len(cross) else 'never (within the horizon)'}**.",
           f"- At the end: mean {s['mean'].iloc[-1]:.3f} (range {s['min'].iloc[-1]:.3f}-{s['max'].iloc[-1]:.3f}).", "",
           *( [f"- Seeded run: on day {D731 - D731 % 7} (week of 2 Oct 2026; seeds on day 233 = 22 May 2025) mean share ever "
               f"infested = {s['mean'].loc[D731 - D731 % 7]:.3f} vs SRA {SRA_SHARE:.3f}.", ""] if SEEDED and (D731 - D731 % 7) in s.index else [] ),
           "A time-scale check only: the observed area was under treatment and partly reflects validation effort (Ch3 3.6.2).", ""]
    fig, ax = plt.subplots(figsize=(7, 3.5))
    nser = read("series/series_none_baseline.csv", SCOLS)
    if nser is not None:
        ns = nser.groupby("cycle").share_ever.mean()
        ncross = ns.index[ns >= SRA_SHARE]
        d0 = D731 - D731 % 7
        md += ["No-control run with the same seeded start (1 run; upper bound of the model for this date):", "",
               f"- Share ever infested in the week of 2 Oct 2026 (day {d0}): none {ns.loc[d0]:.3f}, hybrid {s['mean'].loc[d0]:.3f}, SRA {SRA_SHARE:.3f} of planted cane.",
               f"- In hectares (1 cell = 1 ha, {N_CANE:,} mapped cane cells): none {ns.loc[d0] * N_CANE:,.0f}, hybrid {s['mean'].loc[d0] * N_CANE:,.0f}, SRA validated 72,103.",
               f"- None reaches {SRA_SHARE:.1%} on day {int(ncross[0]) if len(ncross) else 'never'} (2 Oct 2026 = day 731).", "",
               "The observed area is above BOTH model curves: the model spreads too slowly at baseline even without control. "
               "Not a validation; spread parameters and the seed size are uncalibrated.", ""]
        ax.plot(ns.index, ns.values, color="#000", label="no control (1 run)")
    ax.fill_between(s.index, s["min"], s["max"], color="#d9a", alpha=0.4, label="range across runs")
    ax.plot(s.index, s["mean"], color="#a03", label="hybrid, mean share ever infested")
    if SEEDED: ax.plot([D731], [SRA_SHARE], "D", color="#06c", ms=7, label="SRA validated / planted, 2 Oct 2026")
    ax.axhline(SRA_SHARE, color="k", ls="--", lw=1, label="SRA validated share, 2 Oct 2026")
    ax.set_xlabel("Day (from 1 Oct)"); ax.set_ylabel("Share of cane cells"); ax.legend(fontsize=8)
    plt.tight_layout(); fig.savefig(os.path.join(OUT, "timescale.png"), dpi=200); plt.close(fig)
    md += ["![timescale](timescale.png)", ""]

# 3b Severity split vs PGNO survey (seeded runs; levels 1-3 = PGNO per-leaf bins with k_leaf = 100)
# PGNO, as of 8 Nov 2026, survey 22 Jul-8 Nov 2026: Low 8,192, Moderate 4,773, High 2,548 farmlots (of 16,505)
if ser is not None and SEEDED and "lv1" in ser and ser.lv1.notna().any():
    PG = {"lv1": 8192, "lv2": 4773, "lv3": 2548}
    w = ser[(ser.cycle >= 659) & (ser.cycle <= 768)]
    tot = w[["lv1", "lv2", "lv3"]].sum(axis=1)
    sh = {k: (w[k] / tot).mean() for k in PG}
    pt = sum(PG.values())
    md += ["## 3b. Severity split among infested farms vs PGNO survey (weak pattern)", "",
           "Model: hybrid, seeded, mean over weeks in days 659-768 (22 Jul-8 Nov 2026). PGNO: farmlots with RSSI found, "
           "as of 8 Nov 2026. The survey expanded coverage over time (High fell from 28% to 15% as it grew), so this is a "
           "face-validation pattern only.", "",
           "| Level | Model | PGNO |", "|---|---|---|"]
    for k, lab in [("lv1", "1 Low"), ("lv2", "2 Moderate"), ("lv3", "3 High")]:
        md.append(f"| {lab} | {sh[k]:.1%} | {PG[k] / pt:.1%} |")
    md.append("")

# 4 Per-LGU comparison with SRA Table I
lg = read("series/lgu_hybrid_baseline_d731.csv" if SEEDED else "series/lgu_hybrid_baseline.csv", LCOLS)
if lg is not None:
    a = lg.groupby(["lgu_idx", "lgu_name"]).agg(cane=("cane_cells", "first"), ever=("ever_cells", "mean"),
                                                 valid=("sra_valid_ha", "first")).reset_index()
    a = a[(a.cane > 0) & (a.valid >= 0)]
    a["model_share"] = a.ever / a.cane
    a["sra_share"] = a.valid / a.cane          # validated ha over mapped cane ha (1 cell = 1 ha)
    rho = a.model_share.rank().corr(a.sra_share.rank())
    SEED_LGUS = ["Silay City", "City of Talisay", "City of Victorias", "Cadiz City", "Enrique B. Magalona (Saravia)",
                 "Manapla", "Toboso", "Bago City", "La Carlota City", "La Castellana", "Murcia"]
    b = a[~a.lgu_name.isin(SEED_LGUS)]
    rho_ns = b.model_share.rank().corr(b.sra_share.rank()) if len(b) > 2 else float("nan")
    md += ["## 4. Per-municipality comparison with SRA (FOI Table I)", "",
           f"{len(a)} LGUs with cane and an SRA row. Spearman rank correlation between model share ever infested "
           f"and SRA validated share of mapped cane: **{rho:.2f}**; without the 11 seed LGUs (n = {len(b)}): **{rho_ns:.2f}**.", "",
           ("Seeded start (87 cells in the 11 LGUs of 22 May 2025), model read on day 731 = 2 Oct 2026, the FOI date. "
            "The 11 seed LGUs start ahead by construction; the test is whether spread from them reproduces the rest of the ranking." if SEEDED else
           "Caution: the model starts from randomly placed infestations, while the real outbreak started in "
           "northern Negros Occidental (March 2025). A low correlation is expected and is not a failure of the model; "
           "it shows what a seeded start from the first detections would need to reproduce."), ""]
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.scatter(a.sra_share, a.model_share, s=12)
    ax.set_xlabel("SRA validated ha / mapped cane ha"); ax.set_ylabel("Model: share of cane cells ever infested")
    ax.set_title(f"LGUs (n = {len(a)}), Spearman {rho:.2f}")
    plt.tight_layout(); fig.savefig(os.path.join(OUT, "lgu_scatter.png"), dpi=200); plt.close(fig)
    md += ["![lgu](lgu_scatter.png)", ""]

