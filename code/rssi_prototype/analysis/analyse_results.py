# 6 Wind direction
wi = read("wind/batch_wind_direction.csv", COLS)
if wi is not None:
    w = wi.rename(columns={"oat_case": "wind_dir"}).groupby(["strategy", "wind_dir"]).cum_kdays.agg(["mean", "std"]).unstack()
    md += ["## 6. Wind direction (bias 1.0): 135 (from NE) vs 315 (from SW)", ""]
    if ("mean", 135.0) in w.columns and ("mean", 315.0) in w.columns:
        md += ["| Strategy | Load at 135: mean (SD) | Load at 315: mean (SD) | Difference / larger SD |", "|---|---|---|---|"]
        for st, r in w.dropna(subset=[("mean", 135.0), ("mean", 315.0)]).iterrows():
            m1, m2 = r[("mean", 135.0)], r[("mean", 315.0)]
            sd = np.nanmax([r[("std", 135.0)], r[("std", 315.0)]])
            ratio = abs(m1 - m2) / sd if sd and not np.isnan(sd) else float("nan")
            md.append(f"| {st} | {m1:,.0f} ({r[('std', 135.0)]:,.0f}) | {m2:,.0f} ({r[('std', 315.0)]:,.0f}) | {ratio:.1f} |")
        md += ["", "A ratio below about 2 means direction makes no difference beyond run-to-run spread [rule of thumb].", ""]
    else:
        md += [f"Incomplete: only {len(wi)} runs, not both directions yet.", ""]

